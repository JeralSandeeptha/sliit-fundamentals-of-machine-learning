a = 10;
b = 20;

# Basic Operators
print(a + b);
print(a - b);
print(a * b);
print(a / b);
print(a % b);
print(a // b);
print(a ** b);

# Conditional Operators

# Both should be match
a = True;
b = False;

c = a and b;

# Either one should be match
a = True;
b = False;

c = a or b;

# Compare
a = 50;
b = 80;

c = a < b;

# Not Operator
a = False;

b = not a;

# Check variables are equal Operator
a = False;
b = True;

c = a ^ b;

# In Operator
x = [1, 2, 3, 4, 5];
isTrue = 5 in x;

# Not In Operator
x = [1, 2, 3, 4, 5];
isFalse = 10 not in x;